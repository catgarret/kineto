/** Every generated file as { relativePath: content }. Pure. */
export function renderAll(contracts) {
  const rules = renderRules(contracts);
  const files = {
    'docs/integrations/README.md': renderIndex(contracts),
    'docs/integrations/figma-mcp.md': renderFigma(contracts),
    'ai/kineto.rules.md': rules,
    'ai/cursor/kineto.mdc': renderCursorRule(rules),
    'site/llms.txt': renderLlmsTxt(contracts),
    'site/ai/kineto.rules.md': rules
  };
  for (const id of Object.keys(contracts.integrations.ecosystems)) files[`docs/integrations/${id}.md`] = renderEcosystem(id, contracts);
  return files;
}

/** The subset that lives under site/ (used by scripts/build-demo-cdn.mjs). */
export function renderSiteExtras(contracts = loadContracts()) {
  return Object.fromEntries(Object.entries(renderAll(contracts)).filter(([file]) => file.startsWith('site/')));
}

export function writeFiles(files, { check = false } = {}) {
  const stale = [];
  for (const [file, content] of Object.entries(files)) {
    const target = path.join(root, file);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) stale.push(file);
      continue;
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
  return stale;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const contracts = loadContracts();
  const files = renderAll(contracts);
  // Sanity: every module referenced by a recipe exists (the test is stricter).
  for (const intent of contracts.integrations.intents) {
    for (const recipe of intent.recipes) {
      if (!isCorePrimitive(recipe.module) && !findModule(contracts.features, recipe.module)) {
        console.error(`generate-integrations: unknown module ${recipe.module} in intent ${intent.id}`);
        process.exit(1);
      }
      void jsSnippet(recipe, contracts.features);
    }
  }
  const check = process.argv.includes('--check');
  const stale = writeFiles(files, { check });
  if (check) {
    if (stale.length) { console.error(`generate-integrations --check FAILED — stale:\n  - ${stale.join('\n  - ')}`); process.exit(1); }
    console.log(`generate-integrations --check OK — ${Object.keys(files).length} generated files are current.`);
  } else {
    console.log(`Generated ${Object.keys(files).length} integration files (docs/integrations, ai/, site/llms.txt).`);
  }
}
