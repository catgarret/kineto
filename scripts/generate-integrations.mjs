function renderEcosystem(id, { features, integrations, pkg }) {
  const ecosystem = integrations.ecosystems[id];
  const language = frameworkLanguage[ecosystem.framework === 'html' ? 'html' : ecosystem.framework];
  const lines = [];
  lines.push(GENERATED_NOTE, '', `# ${ecosystem.title} + Kineto (v${pkg.version})`, '');
  lines.push(`붙이는 방식: **${ecosystem.attach.pattern}** — ${ecosystem.attach.summary}`, '');
  lines.push(code(language, ecosystem.attach.example), '');
  lines.push('## 설치', '', code('bash', integrations.setup.install), '');
  if (ecosystem.framework === 'react') {
    lines.push('React 앱은 루트 레이아웃에 프로바이더를 한 번 두면 됩니다(클라이언트 컴포넌트). shadcn 레지스트리의 `@kineto/provider`가 아래 컴포넌트를 설치해 주며, 다른 React 앱에서도 같은 코드를 그대로 쓸 수 있습니다.', '');
    lines.push(code('tsx', "'use client';\nimport { useEffect } from 'react';\nimport Kineto from '@dong-gri/kineto';\nimport '@dong-gri/kineto/style.css';\n\nexport function KinetoProvider({ children }: { children: React.ReactNode }) {\n  useEffect(() => {\n    const handle = Kineto.observe();\n    return () => handle.disconnect();\n  }, []);\n  return <>{children}</>;\n}"), '');
  } else if (ecosystem.framework === 'vue') {
    lines.push(code('ts', ecosystem.plugin || "// main.ts\nimport Kineto from '@dong-gri/kineto';\nimport '@dong-gri/kineto/style.css';\nimport KinetoVue from '@dong-gri/kineto/vue';\n\napp.use(KinetoVue);\napp.mount('#app');\nKineto.observe();"), '');
  } else {
    lines.push(code('html', integrations.setup.cdn), '');
  }
  if (ecosystem.registry) {
    lines.push('## shadcn 레지스트리', '', `\`components.json\`에 네임스페이스를 추가하면 \`${ecosystem.registry.install}\`처럼 설치할 수 있습니다. 항목 목록은 [${SITE_URL}/r/registry.json](${SITE_URL}/r/registry.json)에 있습니다.`, '', code('json', ecosystem.registry.componentsJson), '');
  }
  if (ecosystem.provides.length) {
    lines.push('## 이 라이브러리가 이미 제공하는 것', '', `${ecosystem.provides.map((item) => `\`${item}\``).join(', ')} — 동작·접근성은 라이브러리에 맡기고 Kineto는 모션만 더합니다.`, '');
  }
  if (ecosystem.conflicts?.length) {
    lines.push('## 같이 쓰면 안 되는 조합', '');
    ecosystem.conflicts.forEach((conflict) => lines.push(`- ${conflict}`));
    lines.push('');
  }
  if (ecosystem.notes.length) {
    lines.push('## 참고', '');
    ecosystem.notes.forEach((note) => lines.push(`- ${note}`));
    lines.push('');
  }
  if (ecosystem.examples?.length) {
    lines.push('## 예제', '');
    for (const example of ecosystem.examples) {
      const proof = example.test ? ` — 실제 브라우저 검증: [\`${example.test}\`](${REPO_URL}/blob/main/${example.test})` : '';
      lines.push(`- [\`${example.path}\`](${REPO_URL}/blob/main/${example.path}): ${example.title}${proof}`);
    }
    lines.push('');
  }
  lines.push('## 의도별 레시피', '');
  for (const intent of integrations.intents) {
    const guidance = guidanceFor(intent, id, integrations);
    lines.push(`### ${intent.ko} (\`${intent.id}\`)`, '');
    if (guidance.decision === 'prefer-library') {
      lines.push(`이 라이브러리의 **${guidance.equivalent}**를 먼저 씁니다. Kineto 레시피는 그 컴포넌트를 쓰지 않는 페이지에서만 적용합니다.`, '');
    } else if (guidance.decision === 'enhance') {
      lines.push(`**${guidance.equivalent}**가 열림·닫힘과 포커스를 소유합니다. Kineto는 그 안의 콘텐츠에만 모션을 더합니다.`, '');
    }
    intent.recipes.forEach((recipe) => {
      lines.push(`- ${recipeLabel(recipe)} — ${recipe.why}`);
      lines.push('', '  ' + code(language, snippetFor(recipe, features, ecosystem.framework === 'html' ? 'html' : ecosystem.framework)).replace(/\n/g, '\n  '), '');
    });
    (intent.notes || []).forEach((note) => lines.push(`> ${note}`, ''));
  }
  return lines.join('\n');
}

function renderFigma({ integrations }) {
  const lines = [];
  lines.push(GENERATED_NOTE, '', '# Figma MCP → 코드 → Kineto', '');
  lines.push(integrations.figmaHints.description, '');
  lines.push('## 워크플로우', '');
  integrations.figmaHints.workflow.forEach((step, index) => lines.push(`${index + 1}. ${step}`));
  lines.push('', '## 노드 타입 규칙', '', '| 조건 | 의도 |', '|---|---|');
  integrations.figmaHints.nodeTypeRules.forEach((rule) => lines.push(`| ${rule.when} | \`${rule.intent}\` |`));
  lines.push('', '## 레이어 이름 패턴', '', '레이어 이름을 대소문자 구분 없이 아래 정규식과 대조합니다.', '', '| 의도 | 패턴 |', '|---|---|');
  integrations.intents.forEach((intent) => lines.push(`| \`${intent.id}\` | ${intent.figma.map((pattern) => `\`/${pattern}/i\``).join(', ') || '—'} |`));
  lines.push('', '## 에이전트 설정', '', 'Claude Code · Codex · Cursor에 Figma MCP와 함께 Kineto MCP를 등록하면 `kineto_suggest`가 레이어 이름과 생태계를 받아 위 규칙을 실행합니다. 등록 방법은 [`packages/kineto-mcp/README.md`](../../packages/kineto-mcp/README.md)를 보세요. MCP 없이도 [`ai/kineto.rules.md`](../../ai/kineto.rules.md)를 프로젝트 규칙 파일에 넣으면 같은 판단 기준을 읽을 수 있습니다.', '');
  return lines.join('\n');
}

// ---------------------------------------------------------------- AI rules (en)
function renderRules({ features, integrations, pkg }) {
  const lines = [];
  lines.push(`# Kineto rules for coding agents (v${pkg.version})`, '');
  lines.push('Kineto (`@dong-gri/kineto`) is a vanilla-first motion/effects library: 53 modules activated by `data-kt-*` attributes or `Kineto.create()`, with React/Vue/jQuery adapters. Use these rules whenever you generate UI with any component library (shadcn/ui, Bootstrap, MUI, Mantine, Chakra, Ant Design, daisyUI, Nuxt UI, PrimeVue, Vuetify) or from a Figma frame.', '');
  lines.push('## Principles', '');
  integrations.principles.forEach((principle) => lines.push(`- ${principle}`));
  lines.push('', '## Setup (once per app)', '', code('js', `${integrations.setup.css}\n${integrations.setup.bootstrapScript}`), '');
  lines.push('React: mount a client `KinetoProvider` that calls `Kineto.observe()` in an effect (shadcn registry: `npx shadcn@latest add @kineto/provider`). Vue/Nuxt: a client plugin that calls `Kineto.observe()`. Static HTML: the CDN snippet with `Kineto.observe()`.', '');
  lines.push('## Attachment grammar', '');
  lines.push('- Activation: `data-kt-<module-kebab>="<variant>"` (omit the value for the default variant). Options: `data-kt-<option-kebab>="value"`; booleans as bare attributes; arrays/objects as JSON strings.');
  lines.push('- JavaScript: `Kineto.create(\'<module>\', element, { <variantKey>: \'<variant>\', ...options })`. React: `useKineto(\'<module>\', options)` / `<Motion as="h1" type="<module>" options={...}>`. Vue: `v-motion="{ type, options }"` / `useKineto()`.');
  lines.push('- Component libraries forward unknown props/attrs to their root DOM node, so `data-kt-*` on `<Card>`, `<Button>`, `<UCard>`, `<v-card>` … reaches the DOM. If a component does not forward attributes, wrap it in a plain element or use a ref.');
  lines.push('- One transform-writing module per element (tilt, gesture, magnetic, scrollVelocity, parallax, flip). One reveal per section, staggered, rather than one per item.', '');
  lines.push('## Decide by intent', '', '| Intent | Default recipe | When the library already has it |', '|---|---|---|');
  for (const intent of integrations.intents) {
    const first = intent.recipes[0];
    const equivalents = intent.libraryEquivalents ? Object.entries(intent.libraryEquivalents).map(([id, name]) => `${id}: ${name}`).join('; ') : '';
    const mode = intent.provideWhenLibraryHas === 'prefer-library' ? `prefer the library (${equivalents})` : intent.provideWhenLibraryHas === 'enhance' ? `keep the library component, animate its content (${equivalents})` : 'Kineto provides it';
    lines.push(`| ${intent.id} — ${intent.title} (${intent.keywords.slice(0, 4).join(', ')}) | \`${attributeList(first, features)}\` | ${mode} |`);
  }
  lines.push('', '## Figma layer → intent', '');
  for (const rule of integrations.figmaHints.nodeTypeRules) lines.push(`- ${rule.when} → \`${rule.intent}\``);
  lines.push('- Layer-name regexes per intent: ' + integrations.intents.map((intent) => `${intent.id} (${intent.figma.map((pattern) => `/${pattern}/i`).join(' ')})`).join('; '));
  lines.push('', '## Per-ecosystem notes', '');
  for (const [id, ecosystem] of Object.entries(integrations.ecosystems)) {
    const bullets = [...(ecosystem.conflicts || []), ...ecosystem.notes];
    lines.push(`- **${id}** (${ecosystem.attach.pattern}; provides: ${ecosystem.provides.join(', ') || 'nothing — vanilla'})${bullets.length ? ': ' + bullets.join(' ') : ''}`);
  }
  lines.push('', '## Option lookup', '', `Exact option names, variants and defaults live in \`kineto.features.json\` (${RAW_URL}/kineto.features.json) and the generated reference (${REPO_URL}/blob/main/docs/module-reference.md). With the Kineto MCP server (\`npx @dong-gri/kineto-mcp\`) call \`kineto_suggest\`, \`kineto_snippet\` and \`kineto_validate_options\` instead of guessing.`, '');
  // Without this block an agent keeps emitting markup that still works today
  // but is already on its way out — the exact "AI reinvents a slightly
  // different component every time" failure a canonical source exists to stop.
  if (integrations.deprecations?.length) {
    lines.push('## Do not generate these any more', '');
    lines.push('| Instead of | Generate | Why |', '|---|---|---|');
    for (const entry of integrations.deprecations) {
      lines.push(`| \`${entry.use}\` | \`${entry.instead}\` | ${entry.why} |`);
    }
    lines.push('');
    // Several aliases usually share one migration note; print it once.
    for (const note of [...new Set(integrations.deprecations.map((entry) => entry.note).filter(Boolean))]) {
      lines.push(`- ${note}`);
    }
    lines.push('', `The old markup keeps working until ${integrations.deprecations[0].removal} and emits a recoverable \`KT_DEPRECATED\` diagnostic when \`debug\` is on.`, '');
  }
  lines.push('## Modules with their variant keys', '');
  const rows = features.modules.map((module) => `- \`${module.attribute}\` — variants: ${module.variants.join(', ')} (JS key \`${variantKey(module)}\`)`);
  lines.push(...rows, '');
  return lines.join('\n');
}

