// Generate every human- and AI-facing artefact of the integration map from
// kineto.integrations.json (+ kineto.features.json):
//
//   docs/integrations/README.md         overview + intent table (Korean)
//   docs/integrations/<ecosystem>.md    one guide per UI library / design system
//   docs/integrations/figma-mcp.md      Figma MCP → code → Kineto workflow
//   ai/kineto.rules.md                  rules any coding agent can read (English)
//   ai/cursor/kineto.mdc                the same rules as a Cursor rule file
//   site/llms.txt + site/ai/kineto.rules.md   served from the demo site
//
// The map is the single source of truth: edit kineto.integrations.json, then
//   node scripts/generate-integrations.mjs           # write
//   node scripts/generate-integrations.mjs --check   # fail if anything is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { attributeList, findModule, guidanceFor, isCorePrimitive, jsSnippet, snippetFor, variantKey } from './integrations/lib.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE_URL = 'https://kineto.dongri.me';
const REPO_URL = 'https://github.com/catgarret/kineto';
const RAW_URL = 'https://raw.githubusercontent.com/catgarret/kineto/main';

export function loadContracts() {
  const read = (file) => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  return { features: read('kineto.features.json'), integrations: read('kineto.integrations.json'), pkg: read('package.json') };
}

const GENERATED_NOTE = '<!-- Generated by scripts/generate-integrations.mjs from kineto.integrations.json — edit the JSON, not this file. -->';
const code = (language, body) => `\`\`\`${language}\n${body}\n\`\`\``;
const frameworkLanguage = { html: 'html', react: 'jsx', vue: 'vue', js: 'js' };

function recipeLabel(recipe) {
  return recipe.variant ? `\`${recipe.module}\` · \`${recipe.variant}\`` : `\`${recipe.module}\``;
}

function decisionLabel(decision) {
  return decision === 'prefer-library' ? '라이브러리 컴포넌트 우선' : decision === 'enhance' ? '라이브러리 컴포넌트 유지 + Kineto 모션' : 'Kineto 사용';
}

