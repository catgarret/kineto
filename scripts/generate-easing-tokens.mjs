#!/usr/bin/env node
// Easing tokens for plain CSS — generated from src/easings.js so the stylesheet
// and the runtime can never disagree about what "spring-snappy" means.
//
// Writes the block between the markers in src/kineto.css:
//   --kt-spring-<name>           CSS linear() that plays the spring
//   --kt-spring-<name>-duration  its natural duration (rest within 0.1%)
//   --kt-ease-<apple-curve>      Apple's cubic-bezier curves
//
// Use them anywhere, without any Kineto JavaScript:
//   .card { transition: translate var(--kt-spring-snappy-duration) var(--kt-spring-snappy); }
//
// Run:   node scripts/generate-easing-tokens.mjs          (write)
//        node scripts/generate-easing-tokens.mjs --check  (fail when stale; part of test:easings)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { APPLE_BEZIERS, springDuration, toCSS } from '../src/easings.js';

const FILE = fileURLToPath(new URL('../src/kineto.css', import.meta.url));
const START = '/* kt:easing-tokens:start — generated by scripts/generate-easing-tokens.mjs; do not edit */';
const END = '/* kt:easing-tokens:end */';

// The presets worth a CSS token: Apple's three SwiftUI springs, SwiftUI's
// default animation and the interactive (finger-tracking) spring. The legacy
// `spring` token and `spring-classic` stay runtime-only to keep the stylesheet small.
const SPRING_TOKENS = ['spring-smooth', 'spring-snappy', 'spring-bouncy', 'spring-apple', 'spring-interactive'];

export function tokenBlock() {
  const lines = [START, ':root {'];
  for (const name of SPRING_TOKENS) {
    const seconds = Math.round(springDuration(name) * 1000) / 1000;
    lines.push(`  --kt-${name}: ${toCSS(name)};`);
    lines.push(`  --kt-${name}-duration: ${seconds}s;`);
  }
  for (const name of Object.keys(APPLE_BEZIERS)) {
    lines.push(`  --kt-ease-${name}: ${toCSS(name)};`);
  }
  lines.push('}', END);
  return lines.join('\n');
}

export function withTokens(css) {
  const block = tokenBlock();
  const start = css.indexOf(START);
  const end = css.indexOf(END);
  if (start === -1 || end === -1) {
    // First run: insert right after the opening :root block.
    const anchor = css.indexOf('}\n', css.indexOf(':root {')) + 2;
    return `${css.slice(0, anchor)}\n${block}\n${css.slice(anchor)}`;
  }
  return `${css.slice(0, start)}${block}${css.slice(end + END.length)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const current = readFileSync(FILE, 'utf8');
  const next = withTokens(current);
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('src/kineto.css easing tokens are stale — run `node scripts/generate-easing-tokens.mjs`');
      process.exit(1);
    }
    console.log(`easing tokens OK — ${SPRING_TOKENS.length} springs + ${Object.keys(APPLE_BEZIERS).length} Apple curves in src/kineto.css`);
  } else if (next !== current) {
    writeFileSync(FILE, next);
    console.log('Updated easing tokens in src/kineto.css');
  }
}
