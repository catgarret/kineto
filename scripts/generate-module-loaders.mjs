// Generates src/moduleLoaders.js — the name → import() table the
// `@dong-gri/kineto/auto` entry registers with Kineto.registerLazy().
//
// Source of truth: kineto.features.json#modules. A module added to the contract
// becomes loadable on demand without anyone editing a list by hand, and a module
// file that does not exist fails the build instead of failing in a browser.
//
//   node scripts/generate-module-loaders.mjs          write the file
//   node scripts/generate-module-loaders.mjs --check  fail when it is stale (CI)
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = path.join(root, 'kineto.features.json');
const outputPath = path.join(root, 'src/moduleLoaders.js');
const check = process.argv.includes('--check');

const contract = JSON.parse(fs.readFileSync(contractPath, 'utf8'));
const names = contract.modules.map(({ name }) => name).sort();

// Names become object keys and relative import specifiers: accept identifiers only.
const invalid = names.filter((name) => !/^[a-z][A-Za-z0-9]*$/.test(name));
if (invalid.length) throw new Error(`Module names must be identifiers: ${invalid.join(', ')}`);
const missing = names.filter((name) => !fs.existsSync(path.join(root, 'src/modules', `${name}.js`)));
if (missing.length) throw new Error(`Contract modules without src/modules/<name>.js: ${missing.join(', ')}`);

const lines = [
  '// GENERATED by scripts/generate-module-loaders.mjs from kineto.features.json.',
  '// Do not edit: add the module to the contract and run `npm run build`.',
  '//',
  '// One importer per public module. A literal import() path per module is what',
  '// lets every bundler split each module into its own chunk (src/auto.js).',
  'export const moduleLoaders = Object.freeze({',
  // Names are validated identifiers above, so they are safe unquoted.
  ...names.map((name, index) => `  ${name}: () => import('./modules/${name}.js')${index < names.length - 1 ? ',' : ''}`),
  '});',
  ''
];
const next = lines.join('\n');
const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';

if (check) {
  if (current !== next) {
    console.error('src/moduleLoaders.js is stale. Run: node scripts/generate-module-loaders.mjs');
    process.exit(1);
  }
  console.log(`module loaders OK — ${names.length} on-demand modules match the contract.`);
} else {
  if (current !== next) fs.writeFileSync(outputPath, next);
  console.log(`Module loaders: ${names.length} on-demand modules → src/moduleLoaders.js`);
}
