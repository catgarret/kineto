import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { rolldown } from 'rolldown';
import { fixturesFor, onDemandEntries, treeShakenEntries } from './fixture-config.mjs';
import { checkReportTable, formatTable, sizeChunks } from './report.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const reportPath = path.join(root, 'docs/consumer-bundle-size.md');
const fixtures = fixturesFor('rolldown');
const { moduleCount } = JSON.parse(fs.readFileSync(path.join(root, 'kineto.features.json'), 'utf8'));
const LABEL = 'Rolldown consumer entry';
const assertCheck = (condition, message) => {
  if (!condition) {
    console.error(`::error title=Rolldown consumer check failed::${message.replaceAll('\n', ' ')}`);
    throw new Error(message);
  }
};

async function measure({ name, entry, budget, variance = 0 }) {
  const bundle = await rolldown({
    input: path.join(here, 'entries', `${entry}.js`),
    external: ['react', 'react-dom', 'vue'],
    treeshake: true,
    logLevel: 'silent'
  });
  const { output } = await bundle.generate({ format: 'esm', sourcemap: false });
  await bundle.close();
  const chunks = output.filter((item) => item.type === 'chunk');
  assertCheck(chunks.length > 0, `${name} Rolldown fixture emitted no chunks`);
  const size = sizeChunks(chunks);
  assertCheck(size.gzip <= budget + variance, `${name} Rolldown bundle is ${size.gzip.toFixed(1)} KB gzip (budget ≤ ${budget} KB${variance ? ` + ${variance} KB runner variance` : ''})`);
  return { name, ...size, budget, variance };
}

const rows = [];
for (const fixture of fixtures) rows.push(await measure(fixture));
const byName = Object.fromEntries(rows.map((row) => [row.name, row]));
treeShakenEntries.forEach((name) => {
  assertCheck(byName[name].gzip < byName.full.gzip, `Rolldown ${name} must remain smaller than full`);
});

onDemandEntries.forEach((name) => {
  assertCheck(byName[name].lazyFiles >= moduleCount, `Rolldown ${name} must split each of the ${moduleCount} modules into an on-demand chunk (found ${byName[name].lazyFiles})`);
  assertCheck(byName[name].gzip < byName['core-three'].gzip, `Rolldown ${name} first download must stay below core + three modules`);
});

const table = formatTable(rows, LABEL);
const section = [
  '<!-- rolldown-bundle-report:begin -->',
  '## Independent bundler check (Rolldown)',
  '',
  '> Generated by `npm --prefix tests/consumer-bundles run write-report` (Rolldown pass).',
  '> Rolldown is pinned in the fixture lockfile; React and Vue peers remain external.',
  '',
  table,
  '',
  'This uses the same public-entry matrix, product gzip budgets, and modular tree-shaking boundaries as Vite. It is a second bundler signal, not a promise that every bundler produces identical bytes.',
  '<!-- rolldown-bundle-report:end -->'
].join('\n');

console.log(`consumer-bundles-rolldown OK\n${table}`);

if (process.argv.includes('--write')) {
  const current = fs.readFileSync(reportPath, 'utf8');
  const pattern = /<!-- rolldown-bundle-report:begin -->[\s\S]*?<!-- rolldown-bundle-report:end -->/;
  const next = pattern.test(current) ? current.replace(pattern, section) : `${current.trimEnd()}\n\n${section}\n`;
  fs.writeFileSync(reportPath, next);
} else if (process.argv.includes('--check')) {
  const current = fs.readFileSync(reportPath, 'utf8');
  const recorded = current.match(/<!-- rolldown-bundle-report:begin -->([\s\S]*?)<!-- rolldown-bundle-report:end -->/)?.[1] || '';
  const problems = checkReportTable(recorded, rows, LABEL);
  assertCheck(!problems.length, `docs/consumer-bundle-size.md (Rolldown section) is stale (run npm --prefix tests/consumer-bundles run write-report):\n${problems.join('\n')}`);
  console.log('consumer-bundle report OK — the Rolldown section matches the measurements.');
}
